import { chromium, expect } from '@playwright/test';
import { createServer } from 'vite';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
process.env.VITE_SUPABASE_URL = 'https://login-test.supabase.co';
process.env.VITE_SUPABASE_PUBLISHABLE_KEY = 'sb_publishable_test';
process.env.VITE_ENABLE_ROLE_TESTING = 'false';
const server = await createServer({ configFile: fileURLToPath(new URL('../vite.config.ts', import.meta.url)), server: { host: '127.0.0.1', port: 5179 } });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE || undefined, headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext();
  const page = await context.newPage();
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  let failLogin = true;
  let locked = false;
  let expired = false;
  let roleName = 'pic_balai';
  let meRequests = 0;
  const user = { id: '11111111-1111-4111-8111-111111111111', aud: 'authenticated', role: 'authenticated', email: 'test@example.com', app_metadata: {}, user_metadata: {}, created_at: '2026-01-01T00:00:00Z' };
  await page.route('https://login-test.supabase.co/auth/v1/**', async route => {
    if (route.request().url().includes('/logout')) return route.fulfill({ status: 204 });
    if (failLogin) return route.fulfill({ status: 400, json: { error_code: 'invalid_credentials', msg: 'Invalid login credentials' } });
    return route.fulfill({ json: { access_token: 'test-access-token', refresh_token: 'test-refresh-token', token_type: 'bearer', expires_in: 3600, expires_at: Math.floor(Date.now() / 1000) + 3600, user } });
  });
  await page.route('**/api/me', async route => {
    meRequests++;
    assert.equal(route.request().headers().authorization, 'Bearer test-access-token');
    if (expired) return route.fulfill({ status: 401, json: { error: 'Sesi tidak valid atau telah tamat' } });
    if (locked) return route.fulfill({ status: 403, json: { error: 'Profil belum ditautkan atau akaun terkunci' } });
    return route.fulfill({ json: { data: { pengguna_id: 4, auth_user_id: user.id, username: 'pic.test', email: user.email, terkunci: false, peran: [{ peran_id: 1, nama: roleName }, { peran_id: 2, nama: 'admin' }], penugasan: [{ peran_id: 1, scope_balai_id: 18, scope_paket_id: null }] } } });
  });
  await page.route('**/api/paket?**', route => route.fulfill({ json: { data: [{ paket_id: 1, nama_paket: 'Paket Server Uji', status: 'DRAFT' }] } }));
  await page.goto('http://127.0.0.1:5179');
  await expect(page.getByRole('heading', { name: 'Masuk ke Jala Mutu' })).toBeVisible();
  async function login() { await page.getByLabel('Email', { exact: true }).fill(user.email); await page.getByLabel('Password', { exact: true }).fill('test-only-password'); await page.getByRole('button', { name: 'Masuk', exact: true }).click(); }
  await login();
  await expect(page.getByRole('alert')).toHaveText('Email atau password salah.');
  failLogin = false;
  await login();
  await expect(page.locator('.active-role-label')).toHaveText('PIC Balai / Pengguna Jasa');
  await expect(page.locator('.auth-local-notice')).toBeVisible();
  await expect(page.getByTestId('button-switch-role')).toHaveCount(0);
  await page.reload();
  await expect(page.locator('.active-role-label')).toHaveText('PIC Balai / Pengguna Jasa');
  assert.ok(meRequests >= 2, 'Refresh must revalidate the server identity');
  await page.getByRole('button', { name: 'Keluar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Masuk ke Jala Mutu' })).toBeVisible();
  locked = true;
  await login();
  await expect(page.getByRole('alert')).toContainText('terkunci');
  await expect(page.locator('.app-shell')).toHaveCount(0);
  await page.getByRole('button', { name: 'Keluar', exact: true }).click();
  locked = false; roleName = 'pimpinan';
  await login();
  await expect(page.getByText('Paket Server Uji — DRAFT')).toBeVisible();
  await expect(page.locator('.app-shell')).toHaveCount(0);
  await page.getByRole('button', { name: 'Keluar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Masuk ke Jala Mutu' })).toBeVisible();
  roleName = 'pic_balai';
  await login();
  await expect(page.locator('.active-role-label')).toHaveText('PIC Balai / Pengguna Jasa');
  expired = true;
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Masuk ke Jala Mutu' })).toBeVisible();
  await expect(page.locator('.app-shell')).toHaveCount(0);
  assert.deepEqual(errors, []);
  console.log('PASS: wrong password, Bearer token, assigned role, refresh, logout, locked profile, read-only pimpinan, expired session. No real accounts used.');
} finally { await browser?.close(); await server.close(); }
