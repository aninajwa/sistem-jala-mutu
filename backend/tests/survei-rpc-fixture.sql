-- Fixture khusus database PostgreSQL lokal/terisolasi.
-- Jalankan hanya pada database ujian kosong. Tidak berisi identitas atau kredensial nyata.
-- Membuat subset skema yang diperlukan proposal, bukan salinan penuh skema produksi.

do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
end $$;

create schema if not exists auth;
create schema if not exists app_private;
grant usage on schema auth, app_private to authenticated;

create or replace function auth.uid()
returns uuid language sql stable
as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
grant execute on function auth.uid() to authenticated;

create table if not exists public.pengguna (
  pengguna_id integer primary key,
  auth_user_id uuid,
  terkunci boolean
);
create table if not exists public.peran (
  peran_id integer primary key,
  nama varchar
);
create table if not exists public.pengguna_peran (
  pp_id integer primary key,
  pengguna_id integer,
  peran_id integer,
  scope_balai_id integer,
  scope_paket_id integer
);
create table if not exists public.balai (
  balai_id integer primary key
);
create table if not exists public.jenis_survei (
  jenis_survei_id integer primary key,
  kode varchar,
  nama varchar,
  metode_uji varchar,
  satuan_volume varchar,
  sistem_id integer,
  semester_wajib integer,
  aktif boolean
);
create table if not exists public.paket_kontrak (
  paket_id integer primary key,
  balai_id integer,
  penyedia_id integer,
  created_by integer references public.pengguna(pengguna_id),
  foreign key (balai_id) references public.balai(balai_id)
);
create table if not exists public.tim_survei (
  tim_id integer primary key,
  paket_id integer references public.paket_kontrak(paket_id),
  jenis_survei_id integer references public.jenis_survei(jenis_survei_id)
);
create table if not exists public.alat_survei (
  alat_id integer primary key,
  penyedia_id integer,
  jenis_survei_id integer references public.jenis_survei(jenis_survei_id)
);
create table if not exists public.penugasan_alat (
  penugasan_id integer primary key,
  tim_id integer references public.tim_survei(tim_id),
  alat_id integer references public.alat_survei(alat_id),
  mulai date,
  selesai date
);
create table if not exists public.ruas_jalan (
  ruas_id integer primary key,
  balai_id integer references public.balai(balai_id)
);
create table if not exists public.anggota_tim (
  anggota_id integer primary key,
  tim_id integer,
  personel_id integer,
  mulai date,
  selesai date
);
create table if not exists public.uji_coba (
  uji_coba_id integer primary key,
  paket_id integer references public.paket_kontrak(paket_id),
  tim_id integer references public.tim_survei(tim_id),
  jenis_survei_id integer references public.jenis_survei(jenis_survei_id),
  alat_id integer references public.alat_survei(alat_id),
  ruas_id integer references public.ruas_jalan(ruas_id),
  status varchar not null default 'DRAFT'
);
create table if not exists public.sesi_survei (
  sesi_id integer generated by default as identity primary key,
  paket_id integer references public.paket_kontrak(paket_id),
  tim_id integer references public.tim_survei(tim_id),
  ruas_id integer references public.ruas_jalan(ruas_id),
  alat_id integer references public.alat_survei(alat_id),
  operator_id integer,
  pengemudi_id integer,
  tanggal date,
  jam_mulai time without time zone,
  jam_selesai time without time zone,
  lajur varchar(255),
  arah varchar(255),
  cuaca varchar(255),
  kondisi_permukaan varchar(255),
  panjang_tercapai_km numeric,
  link_video varchar(2000),
  status varchar
);
create table if not exists public.data_segmen (
  data_id bigint generated by default as identity primary key,
  sesi_id integer references public.sesi_survei(sesi_id),
  jenis_survei_id integer references public.jenis_survei(jenis_survei_id),
  ruas_id integer references public.ruas_jalan(ruas_id),
  sta_awal numeric,
  sta_akhir numeric,
  lajur varchar,
  nilai_utama numeric,
  atribut_detail jsonb,
  lat numeric,
  lon numeric,
  status_qc varchar,
  versi_aktif integer
);

