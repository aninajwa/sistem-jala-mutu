-- CANDIDATE FOR REVIEW ONLY. Do not install without explicit migration approval.
-- Implements Provider -> PIC scope additions after the Stage 0 preparation
-- checklist is approved. The existing package scope tables and Stage 1 snapshot
-- contract remain authoritative; this migration only appends approved IDs.
begin;

create table public.paket_survei_kontrak_pindaan (
  pindaan_id integer generated by default as identity primary key,
  paket_id integer not null references public.paket_kontrak(paket_id),
  versi integer not null default 1 check (versi >= 1),
  expected_scope_version integer not null check (expected_scope_version >= 1),
  skop_asal jsonb not null check (jsonb_typeof(skop_asal) = 'array'),
  jenis_survei_tambahan integer[] not null
    check (cardinality(jenis_survei_tambahan) between 1 and 50
      and array_position(jenis_survei_tambahan, null) is null),
  tambahan_diminta jsonb not null check (jsonb_typeof(tambahan_diminta) = 'array'),
  status text not null default 'DIAJUKAN'
    check (status in ('DIAJUKAN', 'DISETUJUI', 'DITOLAK')),
  diajukan_oleh integer not null references public.pengguna(pengguna_id),
  diajukan_pada timestamptz not null default clock_timestamp(),
  direview_oleh integer references public.pengguna(pengguna_id),
  direview_pada timestamptz,
  catatan_pic text check (catatan_pic is null or length(catatan_pic) <= 2000),
  versi_skop_diluluskan integer,
  constraint paket_survei_kontrak_pindaan_review_state_check
    check (
      (status = 'DIAJUKAN' and direview_oleh is null and direview_pada is null
        and versi_skop_diluluskan is null)
      or (status = 'DISETUJUI' and direview_oleh is not null and direview_pada is not null
        and versi_skop_diluluskan is not null)
      or (status = 'DITOLAK' and direview_oleh is not null and direview_pada is not null
        and versi_skop_diluluskan is null)
    )
);

create unique index paket_survei_kontrak_pindaan_one_pending_per_package
  on public.paket_survei_kontrak_pindaan(paket_id)
  where status = 'DIAJUKAN';
create index paket_survei_kontrak_pindaan_history_order
  on public.paket_survei_kontrak_pindaan(paket_id, pindaan_id desc);

alter table public.paket_survei_kontrak_pindaan enable row level security;
revoke all on public.paket_survei_kontrak_pindaan from public, anon, authenticated;

create or replace function app_private.assert_scope_amendment_provider(p_paket_id integer)
returns integer
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_actor integer;
  v_package public.paket_kontrak;
  v_preparation_status text;
begin
  if auth.uid() is null then
    raise exception 'Login diperlukan' using errcode = '42501';
  end if;

  -- Serialize authority, Stage 0 status and scope version against package changes.
  select * into v_package
  from public.paket_kontrak
  where paket_id = p_paket_id
  for update;
  if not found then
    raise exception 'Paket tidak ditemukan atau tidak boleh diakses' using errcode = 'P0002';
  end if;

  select u.pengguna_id into v_actor
  from public.pengguna u
  where u.auth_user_id = auth.uid()
    and coalesce(u.terkunci, false) = false
    and exists (
      select 1
      from public.pengguna_peran pp
      join public.peran r using (peran_id)
      where pp.pengguna_id = u.pengguna_id
        and r.nama = 'penyedia_jasa'
        and (pp.scope_paket_id is null or pp.scope_paket_id = v_package.paket_id)
        and (pp.scope_balai_id is null or pp.scope_balai_id = v_package.balai_id)
    );

  if v_actor is null or v_package.created_by is distinct from v_actor then
    raise exception 'Paket tidak ditemukan atau tidak berada dalam kewenangan Penyedia' using errcode = 'P0002';
  end if;

  select q.status into v_preparation_status
  from public.checklist_pengisian q
  join public.checklist_template t using (template_id)
  where q.paket_id = p_paket_id
    and t.no_dokumen = 'JM-PERSIAPAN-TAHAP0'
    and t.revisi = 'DRAFT-01'
  for update of q;

  if v_preparation_status is distinct from 'DISETUJUI' then
    raise exception 'Penambahan jenis survei hanya boleh diajukan setelah Tahap 0 disetujui PIC' using errcode = '55000';
  end if;

  return v_actor;
end;
$function$;

create or replace function app_private.baca_pindaan_scope_survei(p_paket_id integer)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $function$
declare
  v_actor integer;
  v_package public.paket_kontrak;
  v_scope_version integer;
  v_scope jsonb;
  v_amendments jsonb;
begin
  if auth.uid() is null then
    raise exception 'Login diperlukan' using errcode = '42501';
  end if;

  select * into v_package
  from public.paket_kontrak
  where paket_id = p_paket_id;
  if not found then
    raise exception 'Paket tidak ditemukan atau tidak boleh diakses' using errcode = 'P0002';
  end if;

  select u.pengguna_id into v_actor
  from public.pengguna u
  where u.auth_user_id = auth.uid() and coalesce(u.terkunci, false) = false;
  if v_actor is null or not exists (
    select 1
    from public.pengguna_peran pp
    join public.peran r using (peran_id)
    where pp.pengguna_id = v_actor
      and (
        r.nama in ('admin', 'direktorat')
        or (r.nama = 'pic_balai' and pp.scope_balai_id = v_package.balai_id
          and (pp.scope_paket_id is null or pp.scope_paket_id = p_paket_id))
        or (r.nama = 'penyedia_jasa' and v_package.created_by = v_actor
          and (pp.scope_paket_id is null or pp.scope_paket_id = p_paket_id)
          and (pp.scope_balai_id is null or pp.scope_balai_id = v_package.balai_id))
      )
  ) then
    raise exception 'Paket tidak ditemukan atau tidak boleh diakses' using errcode = 'P0002';
  end if;

  select versi into v_scope_version
  from public.paket_survei_kontrak_versi
  where paket_id = p_paket_id;

  select coalesce(jsonb_agg(jsonb_build_object(
      'jenis_survei_id', s.jenis_survei_id,
      'kode', s.kode,
      'nama', s.nama,
      'aktif', s.aktif
    ) order by s.jenis_survei_id), '[]'::jsonb)
  into v_scope
  from public.paket_survei_kontrak ps
  join public.jenis_survei s using (jenis_survei_id)
  where ps.paket_id = p_paket_id;

  select coalesce(jsonb_agg(jsonb_build_object(
      'pindaan_id', a.pindaan_id,
      'versi', a.versi,
      'expected_scope_version', a.expected_scope_version,
      'status', a.status,
      'skop_asal', a.skop_asal,
      'tambahan_diminta', a.tambahan_diminta,
      'diajukan_oleh', a.diajukan_oleh,
      'diajukan_pada', a.diajukan_pada,
      'direview_oleh', a.direview_oleh,
      'direview_pada', a.direview_pada,
      'catatan_pic', a.catatan_pic,
      'versi_skop_diluluskan', a.versi_skop_diluluskan
    ) order by a.pindaan_id desc), '[]'::jsonb)
  into v_amendments
  from public.paket_survei_kontrak_pindaan a
  where a.paket_id = p_paket_id;

  return jsonb_build_object(
    'paket_id', p_paket_id,
    'scope_efektif', jsonb_build_object(
      'state', case when v_scope_version is null then 'unset' else 'defined' end,
      'version', v_scope_version,
      'surveys', v_scope
    ),
    'pindaan', v_amendments
  );
end;
$function$;

create or replace function app_private.ajukan_pindaan_scope_survei(
  p_paket_id integer,
  p_expected_scope_version integer,
  p_jenis_survei_ids integer[]
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_actor integer;
  v_scope_version integer;
  v_current_ids integer[];
  v_added_ids integer[];
  v_before jsonb;
  v_requested jsonb;
  v_request integer;
begin
  v_actor := app_private.assert_scope_amendment_provider(p_paket_id);

  if p_expected_scope_version is null or p_expected_scope_version < 1
    or p_jenis_survei_ids is null or cardinality(p_jenis_survei_ids) < 1
    or cardinality(p_jenis_survei_ids) > 50
    or array_position(p_jenis_survei_ids, null) is not null
    or exists (
      select 1 from unnest(p_jenis_survei_ids) as ids(jenis_survei_id)
      where ids.jenis_survei_id < 1
    ) then
    raise exception 'Versi scope atau pilihan jenis survei tidak valid' using errcode = '22023';
  end if;

  select versi into v_scope_version
  from public.paket_survei_kontrak_versi
  where paket_id = p_paket_id
  for update;
  if v_scope_version is null then
    raise exception 'Skop rasmi paket belum ditetapkan' using errcode = '55000';
  end if;
  if v_scope_version <> p_expected_scope_version then
    raise exception 'Skop rasmi telah berubah; muat semula sebelum mengajukan pindaan' using errcode = '40001';
  end if;

  select coalesce(array_agg(jenis_survei_id order by jenis_survei_id), '{}'::integer[])
  into v_current_ids
  from public.paket_survei_kontrak
  where paket_id = p_paket_id;
  select array_agg(distinct ids.jenis_survei_id order by ids.jenis_survei_id)
  into v_added_ids
  from unnest(p_jenis_survei_ids) as ids(jenis_survei_id);

  if cardinality(v_added_ids) = 0
    or exists (
      select 1 from unnest(v_added_ids) as ids(jenis_survei_id)
      where ids.jenis_survei_id = any(v_current_ids)
    ) then
    raise exception 'Pilih hanya jenis survei yang belum ada dalam skop rasmi' using errcode = '22023';
  end if;
  if exists (
    select 1 from unnest(v_added_ids) as ids(jenis_survei_id)
    left join public.jenis_survei s on s.jenis_survei_id = ids.jenis_survei_id
    where s.jenis_survei_id is null or s.aktif is distinct from true
  ) then
    raise exception 'Jenis survei tambahan mesti wujud dan aktif' using errcode = '22023';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
      'jenis_survei_id', s.jenis_survei_id, 'kode', s.kode, 'nama', s.nama, 'aktif', s.aktif
    ) order by s.jenis_survei_id), '[]'::jsonb)
  into v_before
  from public.paket_survei_kontrak ps
  join public.jenis_survei s using (jenis_survei_id)
  where ps.paket_id = p_paket_id;
  select coalesce(jsonb_agg(jsonb_build_object(
      'jenis_survei_id', s.jenis_survei_id, 'kode', s.kode, 'nama', s.nama, 'aktif', s.aktif
    ) order by s.jenis_survei_id), '[]'::jsonb)
  into v_requested
  from public.jenis_survei s
  where s.jenis_survei_id = any(v_added_ids);

  insert into public.paket_survei_kontrak_pindaan(
    paket_id, expected_scope_version, skop_asal, jenis_survei_tambahan,
    tambahan_diminta, diajukan_oleh
  ) values (
    p_paket_id, v_scope_version, v_before, v_added_ids, v_requested, v_actor
  ) returning pindaan_id into v_request;

  insert into public.audit_trail(
    pengguna_id, tabel, record_id, aksi, nilai_baru, waktu
  ) values (
    v_actor, 'paket_survei_kontrak_pindaan', v_request::text,
    'SUBMIT_PACKAGE_SURVEY_SCOPE_AMENDMENT',
    jsonb_build_object(
      'paket_id', p_paket_id, 'pindaan_id', v_request,
      'expected_scope_version', v_scope_version,
      'skop_asal', v_before, 'tambahan_diminta', v_requested, 'status', 'DIAJUKAN'
    ),
    localtimestamp
  );

  return app_private.baca_pindaan_scope_survei(p_paket_id);
end;
$function$;

create or replace function app_private.review_pindaan_scope_survei(
  p_paket_id integer,
  p_pindaan_id integer,
  p_expected_version integer,
  p_keputusan text,
  p_catatan text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_actor integer;
  v_package public.paket_kontrak;
  v_amendment public.paket_survei_kontrak_pindaan;
  v_scope_version integer;
  v_old_scope jsonb;
  v_new_scope jsonb;
  v_new_version integer;
begin
  if auth.uid() is null then
    raise exception 'Login diperlukan' using errcode = '42501';
  end if;

  -- Package lock serializes review with requests and any approved scope update.
  select * into v_package
  from public.paket_kontrak
  where paket_id = p_paket_id
  for update;
  if not found then
    raise exception 'Paket tidak ditemukan atau tidak boleh diakses' using errcode = 'P0002';
  end if;

  select u.pengguna_id into v_actor
  from public.pengguna u
  join public.pengguna_peran pp using (pengguna_id)
  join public.peran r using (peran_id)
  where u.auth_user_id = auth.uid()
    and coalesce(u.terkunci, false) = false
    and r.nama = 'pic_balai'
    and pp.scope_balai_id = v_package.balai_id
    and (pp.scope_paket_id is null or pp.scope_paket_id = p_paket_id)
  limit 1;
  if v_actor is null then
    raise exception 'Hanya PIC Balai yang ditugaskan boleh menyemak pindaan scope' using errcode = '42501';
  end if;

  if p_pindaan_id is null or p_expected_version is null or p_expected_version < 1
    or p_keputusan is null or p_keputusan not in ('DISETUJUI', 'DITOLAK')
    or (p_catatan is not null and length(p_catatan) > 2000)
    or (p_keputusan = 'DITOLAK' and (p_catatan is null or length(btrim(p_catatan)) = 0)) then
    raise exception 'Keputusan atau catatan pindaan tidak valid' using errcode = '22023';
  end if;

  select * into v_amendment
  from public.paket_survei_kontrak_pindaan
  where pindaan_id = p_pindaan_id and paket_id = p_paket_id
  for update;
  if not found or v_amendment.status <> 'DIAJUKAN' then
    raise exception 'Pindaan tidak ditemukan atau sudah diputuskan' using errcode = '55000';
  end if;
  if v_amendment.diajukan_oleh is distinct from v_package.created_by
    or not exists (
      select 1
      from public.pengguna u
      join public.pengguna_peran pp using (pengguna_id)
      join public.peran r using (peran_id)
      where u.pengguna_id = v_amendment.diajukan_oleh
        and coalesce(u.terkunci, false) = false
        and r.nama = 'penyedia_jasa'
        and (pp.scope_paket_id is null or pp.scope_paket_id = p_paket_id)
        and (pp.scope_balai_id is null or pp.scope_balai_id = v_package.balai_id)
    ) then
    raise exception 'Pemilik paket atau kewenangan Penyedia telah berubah; pindaan tidak boleh diputuskan' using errcode = '55000';
  end if;
  if v_amendment.diajukan_oleh = v_actor then
    raise exception 'Pengaju tidak boleh menyemak pindaan sendiri' using errcode = '42501';
  end if;
  if v_amendment.versi <> p_expected_version then
    raise exception 'Permohonan pindaan telah berubah; muat semula sebelum menyemak' using errcode = '40001';
  end if;

  if p_keputusan = 'DISETUJUI' then
    select versi into v_scope_version
    from public.paket_survei_kontrak_versi
    where paket_id = p_paket_id
    for update;
    if v_scope_version is null or v_scope_version <> v_amendment.expected_scope_version then
      raise exception 'Skop rasmi berubah selepas permohonan; tolak permohonan lama dan ajukan pindaan baharu' using errcode = '40001';
    end if;
    if exists (
      select 1 from unnest(v_amendment.jenis_survei_tambahan) as ids(jenis_survei_id)
      join public.paket_survei_kontrak ps
        on ps.paket_id = p_paket_id and ps.jenis_survei_id = ids.jenis_survei_id
    ) then
      raise exception 'Jenis survei tambahan sudah masuk skop rasmi; muat semula sebelum menyemak' using errcode = '40001';
    end if;
    if exists (
      select 1 from unnest(v_amendment.jenis_survei_tambahan) as ids(jenis_survei_id)
      left join public.jenis_survei s on s.jenis_survei_id = ids.jenis_survei_id
      where s.jenis_survei_id is null or s.aktif is distinct from true
    ) then
      raise exception 'Jenis survei yang diminta tidak lagi aktif; permohonan tidak boleh diluluskan' using errcode = '55000';
    end if;

    select coalesce(jsonb_agg(jsonb_build_object(
        'jenis_survei_id', s.jenis_survei_id, 'kode', s.kode, 'nama', s.nama, 'aktif', s.aktif
      ) order by s.jenis_survei_id), '[]'::jsonb)
    into v_old_scope
    from public.paket_survei_kontrak ps
    join public.jenis_survei s using (jenis_survei_id)
    where ps.paket_id = p_paket_id;

    -- Append only; never delete or rewrite teams, trials, or existing survey links.
    insert into public.paket_survei_kontrak(paket_id, jenis_survei_id)
    select p_paket_id, ids.jenis_survei_id
    from unnest(v_amendment.jenis_survei_tambahan) as ids(jenis_survei_id);

    v_new_version := v_scope_version + 1;
    update public.paket_survei_kontrak_versi
    set versi = v_new_version, diubah_oleh = v_actor, diubah_pada = clock_timestamp()
    where paket_id = p_paket_id;

    select coalesce(jsonb_agg(jsonb_build_object(
        'jenis_survei_id', s.jenis_survei_id, 'kode', s.kode, 'nama', s.nama, 'aktif', s.aktif
      ) order by s.jenis_survei_id), '[]'::jsonb)
    into v_new_scope
    from public.paket_survei_kontrak ps
    join public.jenis_survei s using (jenis_survei_id)
    where ps.paket_id = p_paket_id;

    update public.paket_survei_kontrak_pindaan
    set status = 'DISETUJUI', versi = versi + 1,
        direview_oleh = v_actor, direview_pada = clock_timestamp(),
        catatan_pic = nullif(btrim(p_catatan), ''),
        versi_skop_diluluskan = v_new_version
    where pindaan_id = p_pindaan_id;
  else
    update public.paket_survei_kontrak_pindaan
    set status = 'DITOLAK', versi = versi + 1,
        direview_oleh = v_actor, direview_pada = clock_timestamp(),
        catatan_pic = btrim(p_catatan)
    where pindaan_id = p_pindaan_id;
    v_old_scope := null;
    v_new_scope := null;
    v_new_version := null;
  end if;

  insert into public.audit_trail(
    pengguna_id, tabel, record_id, aksi, nilai_lama, nilai_baru, waktu
  ) values (
    v_actor, 'paket_survei_kontrak_pindaan', p_pindaan_id::text,
    case when p_keputusan = 'DISETUJUI'
      then 'APPROVE_PACKAGE_SURVEY_SCOPE_AMENDMENT'
      else 'REJECT_PACKAGE_SURVEY_SCOPE_AMENDMENT' end,
    jsonb_build_object(
      'status', 'DIAJUKAN', 'versi', v_amendment.versi,
      'scope_version', v_amendment.expected_scope_version,
      'skop_asal', v_amendment.skop_asal,
      'tambahan_diminta', v_amendment.tambahan_diminta
    ),
    jsonb_build_object(
      'status', p_keputusan, 'versi', v_amendment.versi + 1,
      'scope_version', v_new_version, 'skop_sebelum', v_old_scope,
      'skop_selepas', v_new_scope, 'catatan_pic', nullif(btrim(p_catatan), '')
    ),
    localtimestamp
  );

  return app_private.baca_pindaan_scope_survei(p_paket_id);
end;
$function$;

