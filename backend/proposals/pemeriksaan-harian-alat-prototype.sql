-- PROTOTYPE / TEST/QA sahaja. Jangan deploy sebelum kontrak KAK disahkan.
-- Item, hasil, unique key, dan scope tugasan di bawah ialah andaian sementara.
-- Tiada status persetujuan, gate sesi, keputusan QA/QC, atau BA diubah.
-- Bergantung pada app_private.assert_survei_read(integer) daripada
-- survei-sesi-rpc.sql. DDL/FK menyentuh struktur produksi hanya jika seseorang
-- memilih untuk memasang proposal ini; jangan jalankan pada Supabase bersama.

create schema if not exists app_private;

create table if not exists app_private.pemeriksaan_harian_alat_prototype (
  pemeriksaan_id bigint generated by default as identity primary key,
  paket_id integer not null references public.paket_kontrak(paket_id),
  alat_id integer not null references public.alat_survei(alat_id),
  tanggal date not null,
  item_pemeriksaan text not null check (item_pemeriksaan in (
    'GPS', 'BATERAI', 'PENYIMPANAN', 'BOUNCE_TEST_KELAS_I'
  )),
  hasil_pemeriksaan text not null check (hasil_pemeriksaan in (
    'OK', 'BERMASALAH', 'TIDAK_DILAKUKAN'
  )),
  catatan text,
  pencatat_id integer not null references public.pengguna(pengguna_id),
  created_at timestamptz not null default now(),
  constraint pemeriksaan_harian_alat_proto_catatan_length
    check (catatan is null or length(btrim(catatan)) <= 2000),
  constraint pemeriksaan_harian_alat_proto_unique
    unique (paket_id, alat_id, tanggal, item_pemeriksaan)
);

create index if not exists pemeriksaan_harian_alat_proto_list_idx
  on app_private.pemeriksaan_harian_alat_prototype (paket_id, tanggal desc, pemeriksaan_id desc);

alter table app_private.pemeriksaan_harian_alat_prototype enable row level security;
revoke all on table app_private.pemeriksaan_harian_alat_prototype from public, anon, authenticated;

create or replace function app_private.baca_senarai_pemeriksaan_harian_alat_prototype(
  p_paket_id integer,
  p_page integer
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform app_private.assert_survei_read(p_paket_id);
  if p_page is null or p_page < 1 or p_page > 1000000 then
    raise exception 'Halaman pemeriksaan tidak valid' using errcode = '22023';
  end if;

  return coalesce((
    select jsonb_agg(to_jsonb(q) order by q.tanggal desc, q.pemeriksaan_id desc)
    from (
      select pemeriksaan_id, paket_id, alat_id, tanggal, item_pemeriksaan,
        hasil_pemeriksaan, catatan, pencatat_id, created_at
      from app_private.pemeriksaan_harian_alat_prototype
      where paket_id = p_paket_id
      order by tanggal desc, pemeriksaan_id desc
      limit 50 offset ((p_page - 1) * 50)
    ) q
  ), '[]'::jsonb);
end;
$$;

create or replace function app_private.catat_pemeriksaan_harian_alat_prototype(
  p_paket_id integer,
  p_alat_id integer,
  p_tanggal date,
  p_item_pemeriksaan text,
  p_hasil_pemeriksaan text,
  p_catatan text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor integer;
  v_user public.pengguna;
  v_package public.paket_kontrak;
  v_result app_private.pemeriksaan_harian_alat_prototype;
begin
  if auth.uid() is null then
    raise exception 'Login diperlukan' using errcode = '42501';
  end if;

  select * into v_user
  from public.pengguna
  where auth_user_id = auth.uid() and not coalesce(terkunci, false);
  if not found or not exists (
    select 1 from public.pengguna_peran pp
    join public.peran r using (peran_id)
    where pp.pengguna_id = v_user.pengguna_id and r.nama = 'penyedia_jasa'
  ) then
    raise exception 'Hanya Penyedia Jasa aktif boleh mencatat pemeriksaan TEST/QA' using errcode = '42501';
  end if;
  v_actor := v_user.pengguna_id;

  select * into v_package
  from public.paket_kontrak
  where paket_id = p_paket_id
  for share;
  if not found then raise exception 'Paket tidak ditemukan' using errcode = 'P0002'; end if;
  if v_package.created_by is distinct from v_actor then
    raise exception 'Akses ke paket ini ditolak' using errcode = '42501';
  end if;

  if p_alat_id is null or p_tanggal is null
    or p_item_pemeriksaan is null
    or p_item_pemeriksaan not in ('GPS', 'BATERAI', 'PENYIMPANAN', 'BOUNCE_TEST_KELAS_I')
    or p_hasil_pemeriksaan is null
    or p_hasil_pemeriksaan not in ('OK', 'BERMASALAH', 'TIDAK_DILAKUKAN')
    or (p_catatan is not null and length(btrim(p_catatan)) > 2000) then
    raise exception 'Data pemeriksaan harian alat TEST/QA tidak valid' using errcode = '22023';
  end if;

  -- Prototipe menganggap alat harus ditugaskan ke tim pada paket dan tanggal
  -- pemeriksaan. Ini bukan gate bagi sesi survei dan tidak mengubah status.
  perform 1
  from public.penugasan_alat pa
  join public.tim_survei t on t.tim_id = pa.tim_id
  join public.alat_survei a on a.alat_id = pa.alat_id
  where t.paket_id = p_paket_id
    and a.alat_id = p_alat_id
    and a.penyedia_id = v_package.penyedia_id
    and a.jenis_survei_id = t.jenis_survei_id
    and (pa.mulai is null or pa.mulai <= p_tanggal)
    and (pa.selesai is null or pa.selesai >= p_tanggal)
  limit 1
  for share of pa, t, a;
  if not found then
    raise exception 'Alat tidak ditugaskan pada paket ini untuk tanggal pemeriksaan' using errcode = '22023';
  end if;

  insert into app_private.pemeriksaan_harian_alat_prototype (
    paket_id, alat_id, tanggal, item_pemeriksaan, hasil_pemeriksaan, catatan, pencatat_id
  ) values (
    p_paket_id, p_alat_id, p_tanggal, p_item_pemeriksaan, p_hasil_pemeriksaan,
    nullif(btrim(p_catatan), ''), v_actor
  ) returning * into v_result;

  return to_jsonb(v_result);
exception
  when unique_violation then
    raise exception 'Item pemeriksaan alat ini sudah dicatat untuk tanggal tersebut' using errcode = '23505';
end;
$$;

